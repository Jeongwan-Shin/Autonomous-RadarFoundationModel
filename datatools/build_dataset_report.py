def ego_sample(text, keep=7):
    """The ego line with the middle bins dropped.

    Twenty bins run to three printed lines and say one thing -- the format, and
    that the channels barely move within the window. Seven carry that.
    """
    head, _, bins = text.partition("): ")
    parts = bins.split()
    if len(parts) <= keep + 1:
        return text
    kept = parts[:keep] + [f"... ({len(parts) - keep - 1}개 생략) ...", parts[-1]]
    return f"{head}): " + " ".join(kept)


def sample_text(text, width=700):
    """A real prompt string as a quotable block: XML-safe, elided line-wise.

    Clipping by character count alone mangles the tracking prompts -- four
    history lines and a closing instruction, where the instruction is the part
    that matters and sits last. Dropping whole middle lines keeps both ends.
    """
    esc = lambda t: (t.replace("&", "&amp;").replace("<", "&lt;")
                     .replace(">", "&gt;"))
    lines = (text or "").strip().split("\n")
    # Length, not line count, decides. A QA prompt is seven short lines and the
    # five options are the point of it; a tracking prompt is six lines of which
    # four are hundreds of characters of history.
    if len(lines) > 5 and len(text) > 900:
        lines = (lines[:2] + [f"... ({len(lines) - 4}줄 생략) ..."] + lines[-2:])
    out = []
    for line in lines:
        if len(line) > width:
            line = line[:width].rsplit(";", 1)[0] + " ... (이하 생략)"
        out.append(esc(line))
    return "<br/>".join(out)


